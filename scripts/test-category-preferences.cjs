const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('src/constants/categories.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {} };
vm.runInNewContext(compiled, context);
const { DEFAULT_BUDGET_CATEGORIES: defaults, mergeWithDefaultCategories: merge } = context.exports;
assert.equal(merge([]).reduce((sum, item) => sum + (item.limitAmount || 0), 0), 0);
const base = defaults[0];
const override = { ...base, id: 'persisted-category', defaultCategoryId: base.id, name: 'Renamed category', limitAmount: 123 };
const renamed = merge([override]);
assert.equal(renamed.filter((item) => item.name === base.name).length, 0);
assert.equal(renamed.find((item) => item.id === override.id).limitAmount, 123);
assert.equal(merge([{ ...override, limitAmount: 0 }]).find((item) => item.id === override.id).limitAmount, 0);
const deleted = merge([{ ...override, deleted: true }]);
assert.equal(deleted.some((item) => item.name === base.name || item.id === override.id), false);
assert.equal(merge(defaults.map((item) => ({ ...item, deleted: true, defaultCategoryId: item.id }))).length, 0);
assert.equal(merge([{ ...base, id: 'legacy-id', deleted: true }]).some((item) => item.name === base.name), false);
console.log('Passed: zero default budget, rename, saved limit, remove limit, default deletion, delete all, legacy deletion.');
